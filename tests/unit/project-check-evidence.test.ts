import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {FabricDatabase} from '../../electron/fabric/FabricDatabase';
import {ProjectCheckEvidence, type ProjectSnapshot} from '../../electron/dev/ProjectCheckEvidence';
import {TaskContinuity} from '../../electron/connected/TaskContinuity';
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'jarvis-project-proof-'));
const file = path.join(directory, 'fabric.sqlite'); let db = new FabricDatabase(file);
let snapshot: ProjectSnapshot = {root: directory, files: [{path: 'package.json', hash: 'manifest-v1'}, {path: 'test.js', hash: 'test-v1'}, {path: 'math.js', hash: 'bad-source'}]};
const take = async () => structuredClone(snapshot), gate = () => {};
let service = new ProjectCheckEvidence(() => db, take);
const checks = [{id: 'test', label: 'Tests', request: {executable: 'npm', args: ['test']}}];
const args = {executable: 'npm', args: ['test'], verification: 'test'};
const result = (exitCode: number) => ({commandId: 'owned-contract-process', exitCode, stdout: 'tests passed', stderr: '', cancelled: false, timedOut: false});
let passed = 0; const pass = (s: string) => {passed++; console.log('PASS ' + s);};
await service.seal('repair', directory, checks, 1, gate);
assert.equal((await service.verify('repair', gate))?.state, 'IMPLEMENTED'); pass('No execution cannot become VERIFIED');
await service.observe('repair', args, async () => result(1), gate);
assert.equal((await service.verify('repair', gate))?.state, 'FAILED'); pass('Failure exit cannot be replaced by optimistic stdout');
snapshot.files[2]!.hash = 'repaired-source';
await service.observe('repair', args, async () => result(0), gate);
const proof = await service.verify('repair', gate);
assert.equal(proof?.state, 'VERIFIED'); assert.equal(proof?.observations.length, 2); pass('Latest real contract observation on unchanged criteria certifies a repaired snapshot; failure kept');
snapshot.files[2]!.hash = 'source-edited-after-tests';
assert.equal((await service.verify('repair', gate))?.state, 'REVIEW_REQUIRED'); pass('Edit after test invalidates current proof');
await service.seal('tamper', directory, checks, 1, gate);
snapshot.files[1]!.hash = 'tests-disabled'; let calls = 0;
await assert.rejects(service.observe('tamper', args, async () => {calls++; return result(0);}, gate), /CHECK_INPUTS_CHANGED/);
assert.equal(calls, 0); assert.equal((await service.verify('tamper', gate))?.state, 'REVIEW_REQUIRED'); pass('Changing criteria cannot hide a failure or run the altered check as original');
await service.seal('forged', directory, checks, 1, gate);
await assert.rejects(service.observe('forged', {...args, args: ['--version']}, async () => {calls++; return result(0);}, gate), /CHECK_COMMAND_MISMATCH/);
await assert.rejects(service.observe('forged', {...args, envSubset: {NODE_OPTIONS: '--require injected.js'}}, async () => result(0), gate), /CHECK_COMMAND_MISMATCH/);
assert.equal(calls, 0); pass('Verification label cannot authorize another command or environment');
await service.seal('self-write', directory, checks, 1, gate);
await service.observe('self-write', args, async () => {snapshot.files[2]!.hash = 'changed-during-test'; return result(0);}, gate);
assert.equal((await service.verify('self-write', gate))?.state, 'REVIEW_REQUIRED'); pass('Self-mutating check cannot certify its post-write snapshot');
await service.seal('stopped', directory, checks, 1, gate);
let revoked = false;
await assert.rejects(service.observe('stopped', args, async () => {service.interrupt('stopped'); revoked = true; return result(0);}, () => {if (revoked) throw Error('STOPPED');}), /STOPPED/);
assert.equal(service.read('stopped')?.state, 'INTERRUPTED'); pass('Late success after STOP cannot overwrite interruption');
await service.seal('restart', directory, checks, 1, gate); db.close(); db = new FabricDatabase(file);
new TaskContinuity(db, path.join(directory,'connected'));
assert.equal(db.operationRecord('project-checks:restart') && (db.operationRecord('project-checks:restart') as {status:string}).status, 'STARTED');
pass('Connected continuity ignores foreign project receipts in the shared journal');
service = new ProjectCheckEvidence(() => db, take);
assert.equal((await service.verify('restart', gate))?.state, 'INTERRUPTED');
await assert.rejects(service.seal('restart', directory, checks, 1, gate), /CHECK_PROOF_NEW_RUN_REQUIRED/); pass('SQLite restart interrupts pending work without replay or resealing');
assert.equal(service.read('repair')?.observations.length, 2); pass('Original failure and successful observation survive restart');
assert.equal((await service.verify('repair', gate))?.state, 'REVIEW_REQUIRED'); pass('A stale historical snapshot remains review-required after restart, not pending work');
db.close();
fs.writeFileSync(path.resolve(process.env.JARVIS_PROJECT_CHECK_EVIDENCE ?? path.join(directory, 'result.json')), JSON.stringify({status: 'PASS', checks: passed, storage: 'REAL_SQLITE', commandExecution: 'SIMULATED_CONTRACT', directory, test: true}, null, 2));
console.log('PROJECT_CHECK_EVIDENCE_PASS ' + passed);
